import { randomUUID } from "node:crypto";
import { tryGetCurrentAuthEndpointContext } from "@better-auth/core/context";
import type { BetterAuthOptions } from "better-auth";
import type { DBAdapter, DBTransactionAdapter } from "better-auth/adapters";
import { APIError, getOAuthState } from "better-auth/api";
import { z } from "zod";
import {
  type AccountBootstrap,
  bootstrapFromCookie,
  bootstrapProofSchema,
  openBootstrap,
} from "./bootstrap-proof";
import { isAuthRole } from "./permissions";

async function requestBootstrap(
  origin: string,
  secret: string
): Promise<AccountBootstrap> {
  const context = tryGetCurrentAuthEndpointContext();
  if (!context?.headers) {
    throw new APIError("FORBIDDEN", { message: "Start account setup again" });
  }
  try {
    if ((context.path ?? "").startsWith("/callback/")) {
      const state = await getOAuthState();
      const proof = bootstrapProofSchema.parse(
        state?.serverContext?.accountBootstrap
      );
      if (proof.expiresAt <= Date.now()) {
        throw new Error("Expired setup");
      }
      return proof;
    }
    if (context.path === "/magic-link/verify" && context.request) {
      const sealed = new URL(context.request.url).searchParams.get("admission");
      if (!sealed) {
        throw new Error("Missing setup");
      }
      return openBootstrap(sealed, secret);
    }
    return bootstrapFromCookie(context.headers, origin, secret);
  } catch (cause) {
    throw new APIError("FORBIDDEN", {
      cause,
      message: "Start account setup again",
    });
  }
}

interface InvitationRow {
  email: string;
  expiresAt: Date;
  id: string;
  organizationId: string;
  role: string;
  status: string;
}
const createdUser = z.object({
  email: z.email(),
  id: z.uuid(),
  name: z.string(),
});

async function joinInvitation(
  adapter: DBTransactionAdapter,
  invitationId: string,
  identity: z.infer<typeof createdUser>,
  now: Date
): Promise<void> {
  const invitation = await adapter.findOne<InvitationRow>({
    model: "invitation",
    where: [{ field: "id", value: invitationId }],
  });
  if (
    invitation?.status !== "pending" ||
    invitation.expiresAt <= now ||
    invitation.email.toLowerCase() !== identity.email.toLowerCase() ||
    !isAuthRole(invitation.role)
  ) {
    throw new APIError("FORBIDDEN", {
      message: "This invitation is no longer available for this email",
    });
  }
  const claimed = await adapter.updateMany({
    model: "invitation",
    update: { status: "accepted" },
    where: [
      { field: "id", value: invitation.id },
      { field: "status", value: "pending" },
      { field: "expiresAt", operator: "gt", value: now },
    ],
  });
  if (claimed !== 1) {
    throw new APIError("CONFLICT", {
      message: "This invitation has already been used",
    });
  }
  await adapter.create({
    data: {
      createdAt: now,
      organizationId: invitation.organizationId,
      role: invitation.role,
      userId: identity.id,
    },
    model: "member",
  });
}

export function withAccountProvisioning(
  factory: (options: BetterAuthOptions) => DBAdapter,
  origin: string,
  secret: string,
  readBootstrap: () => Promise<AccountBootstrap> = () =>
    requestBootstrap(origin, secret)
): (options: BetterAuthOptions) => DBAdapter {
  return (options) => {
    const root = factory(options);
    const provision = (
      adapter: DBTransactionAdapter
    ): DBTransactionAdapter => ({
      ...adapter,
      create: async <T extends Record<string, unknown>, R = T>(args: {
        model: string;
        data: Omit<T, "id">;
        select?: string[];
        forceAllowId?: boolean;
      }): Promise<R> => {
        if (args.model !== "user") {
          return adapter.create<T, R>(args);
        }
        const proof = bootstrapProofSchema.parse(await readBootstrap());
        if (proof.expiresAt <= Date.now()) {
          throw new APIError("FORBIDDEN", {
            message: "Start account setup again",
          });
        }
        // IDs are generated by the adapter. Validate its result instead of
        // treating request-supplied identity fields as authoritative.
        const result = await adapter.create<T, R>(args);
        const identity = createdUser.parse(result);
        if (
          proof.email &&
          proof.email.toLowerCase() !== identity.email.toLowerCase()
        ) {
          throw new APIError("FORBIDDEN", {
            message: "The account link does not match this email",
          });
        }
        const now = new Date();
        if (proof.invitationId) {
          await joinInvitation(adapter, proof.invitationId, identity, now);
        } else {
          const account = await adapter.create<
            Record<string, unknown>,
            { id: string }
          >({
            data: {
              countryCode: proof.countryCode,
              createdAt: now,
              metadata: JSON.stringify({
                bootstrapTimeZone: proof.timeZone,
                bootstrapUserId: identity.id,
              }),
              name: `${identity.name.trim().slice(0, 100) || identity.email.split("@")[0]}'s Account`,
              provisioningStatus: "pending",
              slug: `account-${randomUUID()}`,
            },
            model: "organization",
          });
          await adapter.create({
            data: {
              createdAt: now,
              organizationId: account.id,
              role: "owner",
              userId: identity.id,
            },
            model: "member",
          });
        }
        return result;
      },
    });
    return {
      ...root,
      create: async (args) =>
        args.model === "user"
          ? root.transaction((transaction) =>
              provision(transaction).create(args)
            )
          : root.create(args),
      transaction: (callback) =>
        root.transaction((transaction) => callback(provision(transaction))),
    };
  };
}
